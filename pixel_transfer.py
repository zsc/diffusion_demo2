"""Strict resolution transfer: learned weights only; fresh optimizer and EMA age."""
import hashlib
import inspect
from pathlib import Path

import torch

from diffusion_demo.core.models.pixel_jit import PixelJiT


def inherit_pixel_weights(model, checkpoint):
    state = torch.load(checkpoint, map_location="cpu", weights_only=False)
    source = {k: p.default for k, p in inspect.signature(PixelJiT).parameters.items()}
    source.update(state["config"]["model"])
    for key, value in model.config.items():
        if key not in {"image_size", "position_scale"} and source[key] != value:
            raise ValueError(f"Resolution transfer cannot change {key}: {source[key]} -> {value}")
    # pos/RoPE are non-persistent analytic buffers, regenerated by the target model.
    # Strict loading prevents a silently random input/output layer or Transformer.
    model.load_state_dict(state["ema"], strict=True)
    return dict(checkpoint=str(checkpoint),
                checkpoint_sha256=hashlib.sha256(Path(checkpoint).read_bytes()).hexdigest(),
                weights="ema", source_model=source, target_model=model.config,
                source_images_seen=state.get("images_seen"),
                copied_parameters=sum(p.numel() for p in model.parameters()),
                learned_parameters_reinitialized=0, optimizer="fresh", ema="copied source EMA; fresh age")
